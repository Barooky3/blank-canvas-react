// Generates small, stable PNG thumbnails of every catalog product for the
// order-confirmation email, plus a map the edge function imports.
// Run: SHARP_MODULE=/path/to/node_modules/sharp node scripts/build-email-images.mjs
import { build } from "esbuild";
import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const require = createRequire(import.meta.url);
const sharp = require(process.env.SHARP_MODULE || "sharp");

const outDir = path.join(root, "public/email/products");
const mapFile = path.join(root, "supabase/functions/send-order-confirmation/product-images.ts");
const SIZE = 240;

const bundled = path.join(root, "node_modules/.cache/email-products.mjs");
await build({
  entryPoints: [path.join(root, "src/data/products.ts")],
  bundle: true,
  format: "esm",
  platform: "node",
  outfile: bundled,
  alias: { "@": path.join(root, "src") },
  logLevel: "error",
  plugins: [
    {
      name: "image-paths",
      setup(b) {
        b.onLoad({ filter: /\.(png|jpe?g|webp|avif|gif)$/i }, (args) => ({
          contents: `export default ${JSON.stringify("file:" + args.path)};`,
          loader: "js",
        }));
      },
    },
  ],
});
const { products } = await import(pathToFileURL(bundled).href + "?t=" + Date.now());

function sourceFile(image) {
  if (!image) return null;
  if (typeof image === "object" && image.url) image = image.url;
  if (typeof image !== "string") return null;
  if (image.startsWith("file:")) return image.slice(5);
  if (image.startsWith("/")) {
    const p = path.join(root, "public", decodeURIComponent(image.split("?")[0]));
    return fs.existsSync(p) ? p : null;
  }
  return null;
}

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const entries = [];
const missing = [];
for (const p of products) {
  const candidates = [p.image, ...(p.images || [])];
  const src = candidates.map(sourceFile).find(Boolean);
  if (!src) {
    missing.push(`${p.id} (${p.name})`);
    continue;
  }
  const file = `${p.id}.png`;
  await sharp(src)
    .trim({ threshold: 1 })
    .resize(SIZE, SIZE, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .png({ compressionLevel: 9, palette: true, quality: 90 })
    .toFile(path.join(outDir, file));
  entries.push({ id: p.id, name: p.name, brand: p.brand, path: `/email/products/${file}` });
}

const body = entries
  .map((e) => `  { id: ${JSON.stringify(e.id)}, name: ${JSON.stringify(e.name)}, brand: ${JSON.stringify(e.brand ?? "")}, path: ${JSON.stringify(e.path)} },`)
  .join("\n");
fs.writeFileSync(
  mapFile,
  `// Generated by scripts/build-email-images.mjs. Do not edit by hand.\nexport interface EmailProductImage {\n  id: string;\n  name: string;\n  brand: string;\n  path: string;\n}\n\nexport const EMAIL_PRODUCT_IMAGES: EmailProductImage[] = [\n${body}\n];\n`,
);

console.log(`generated ${entries.length} thumbnails`);
if (missing.length) console.log("no image:", missing.join(", "));
